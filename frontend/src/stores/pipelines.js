import { parseColor } from '@/utils'
import { defineStore } from 'pinia'
import { call } from 'frappe-ui'
import { ref, computed } from 'vue'

const API = 'crm.api.pipeline.'

export const pipelinesStore = defineStore('crm-pipelines', () => {
  const pipelines = ref([])
  const loaded = ref(false)
  let loading = null

  // stage key (CRM Deal Status name) -> { ...stage, pipeline }
  const stagesByKey = computed(() => {
    let map = {}
    for (let p of pipelines.value) {
      for (let s of p.stages || []) {
        map[s.name] ||= { ...s, pipeline: p.name }
      }
    }
    return map
  })

  function apiCall(method, args = {}) {
    return call(API + method, args)
  }

  function normalize(list) {
    return (list || [])
      .map((p) => ({
        ...p,
        stages: (p.stages || [])
          .map((s) => ({ ...s, colorClass: parseColor(s.color) }))
          .sort((a, b) => a.position - b.position),
      }))
      .sort((a, b) => a.position - b.position)
  }

  function fetch() {
    loading = (async () => {
      try {
        pipelines.value = normalize(await apiCall('get_pipelines'))
      } catch (error) {
        // without funnels the menu and Kanban stay empty; nothing else to do here
        console.error('[pipelines] could not load the funnels', error)
        pipelines.value = []
      } finally {
        loaded.value = true
      }
      return pipelines.value
    })()
    return loading
  }

  function ensureLoaded() {
    return loading || fetch()
  }

  function reload() {
    loading = null
    assignableCache = {}
    pipelineUsers = null
    configCache = {}
    catalogPromise = null
    return fetch()
  }

  function getPipeline(name) {
    return pipelines.value.find((p) => p.name === name)
  }

  const defaultPipeline = computed(() => pipelines.value[0] || null)

  // Stage keys are unique across funnels; with the funnel the lookup is direct
  function getStage(stageKey, pipeline = null) {
    if (pipeline) {
      let s = getPipeline(pipeline)?.stages.find((s) => s.name === stageKey)
      if (s) return { ...s, pipeline }
    }
    return stagesByKey.value[stageKey]
  }

  // Display name of a stage. Stage keys are generated by the server, so the
  // key must never reach the screen; fall back to the key only for statuses
  // that do not belong to any funnel the user can see. Default stages are
  // stored in English ("Qualification"), so names go through translation.
  function stageLabel(stageKey, pipeline = null) {
    let label = getStage(stageKey, pipeline)?.deal_status
    return label ? __(label) : stageKey
  }

  // Funnel config and field catalog, cached; reload() clears them
  let configCache = {}
  let catalogPromise = null
  function getConfig(pipeline) {
    configCache[pipeline] ||= apiCall('get_pipeline_config', {
      pipeline,
    }).catch((e) => {
      delete configCache[pipeline]
      throw e
    })
    return configCache[pipeline]
  }

  // { limit, used, fields: [{ fieldname, label, fieldtype, options, ... }] }
  function getCatalog() {
    catalogPromise ||= apiCall('get_field_catalog').catch((e) => {
      catalogPromise = null
      throw e
    })
    return catalogPromise
  }

  // Fields a funnel's cards show: { used: [fieldnames], catalog: [fieldnames] }
  async function fieldSetup(pipeline) {
    if (!pipeline) return null
    let [config, catalog] = await Promise.all([
      getConfig(pipeline),
      getCatalog(),
    ])
    return {
      used: (config?.fields || []).map((f) =>
        typeof f === 'string' ? f : f.fieldname,
      ),
      catalog: (catalog?.fields || []).map((f) => f.fieldname),
      // card fields that belong to the organization now (credtech#181)
      moved: (catalog?.moved || []).map((f) => f.fieldname),
    }
  }

  // Who can own or be assigned a card of a funnel: its members and the admins
  // (crm.permissions.pipeline). Cached per funnel; reload() clears it.
  let assignableCache = {}
  let pipelineUsers = null
  function getPipelineUsers() {
    pipelineUsers ||= apiCall('get_pipeline_users').catch((e) => {
      pipelineUsers = null
      throw e
    })
    return pipelineUsers
  }

  async function assignableUsers(pipeline) {
    if (!pipeline) return null
    assignableCache[pipeline] ||= (async () => {
      let [config, users] = await Promise.all([
        getConfig(pipeline),
        getPipelineUsers(),
      ])
      let names = new Set((config?.members || []).map((m) => m.user))
      for (let u of users?.users || []) if (u.is_admin) names.add(u.name)
      return [...names]
    })().catch((e) => {
      delete assignableCache[pipeline]
      throw e
    })
    return assignableCache[pipeline]
  }

  // Admins and Pipeline Owners may create funnels: the sidebar shows them a
  // shortcut to a new funnel (crm.api.pipeline.get_pipeline_users)
  const canCreate = ref(false)
  async function loadCanCreate() {
    try {
      canCreate.value = Boolean((await getPipelineUsers())?.can_create)
    } catch {
      canCreate.value = false
    }
    return canCreate.value
  }

  return {
    pipelines,
    loaded,
    canCreate,
    loadCanCreate,
    defaultPipeline,
    ensureLoaded,
    reload,
    getPipeline,
    getStage,
    stageLabel,
    assignableUsers,
    fieldSetup,
    getCatalog,
    apiCall,
  }
})
