import { parseColor } from '@/utils'
import { defineStore } from 'pinia'
import { call } from 'frappe-ui'
import { ref, computed } from 'vue'

const API = 'crm.api.pipeline.'

// While the server side of the funnels (#67–#69) is not merged, development
// builds fall back to src/data/pipelineMocks.js. Production builds always talk
// to the server: import.meta.env.DEV is false there, so the mock module is
// dropped from the bundle.
let mockModule = null
async function loadMocks() {
  if (!import.meta.env.DEV) return null
  mockModule ||= await import('@/data/pipelineMocks.js')
  return mockModule
}

export const pipelinesStore = defineStore('crm-pipelines', () => {
  const pipelines = ref([])
  const loaded = ref(false)
  const usingMocks = ref(false)
  let loading = null

  // stage key (CRM Deal Status name) -> { ...stage, pipeline }
  const stagesByKey = computed(() => {
    let map = {}
    for (let p of pipelines.value) {
      for (let s of p.stages || []) {
        map[s.name] ||= { ...s, pipeline: p.name }
      }
    }
    return map
  })

  async function apiCall(method, args = {}) {
    if (usingMocks.value) {
      let mocks = await loadMocks()
      return mocks.mockCall(method, args)
    }
    try {
      return await call(API + method, args)
    } catch (error) {
      // Development only: functions that the server side has not merged yet
      // (e.g. get_stage_rules before #69) fall back to the mock one by one.
      let mocks = isMissingMethod(error) ? await loadMocks() : null
      if (!mocks) throw error
      console.warn(`[pipelines] ${method} not on the server yet, using mock`)
      return mocks.mockCall(method, args)
    }
  }

  function isMissingMethod(error) {
    let text = [error?.message, ...(error?.messages || [])].join(' ')
    return /Failed to get method|has no attribute|No module named/.test(text)
  }

  function normalize(list) {
    return (list || [])
      .map((p) => ({
        ...p,
        stages: (p.stages || [])
          .map((s) => ({ ...s, colorClass: parseColor(s.color) }))
          .sort((a, b) => a.position - b.position),
      }))
      .sort((a, b) => a.position - b.position)
  }

  function fetch() {
    loading = (async () => {
      try {
        pipelines.value = normalize(await call(API + 'get_pipelines'))
      } catch (error) {
        let mocks = await loadMocks()
        if (!mocks) throw error
        console.warn(
          '[pipelines] server API unavailable, using mock data',
          error,
        )
        usingMocks.value = true
        pipelines.value = normalize(await mocks.mockCall('get_pipelines'))
      } finally {
        loaded.value = true
      }
      return pipelines.value
    })()
    return loading
  }

  function ensureLoaded() {
    return loading || fetch()
  }

  function reload() {
    loading = null
    assignableCache = {}
    pipelineUsers = null
    return fetch()
  }

  function getPipeline(name) {
    return pipelines.value.find((p) => p.name === name)
  }

  const defaultPipeline = computed(() => pipelines.value[0] || null)

  // Real stage keys are unique across funnels; passing the funnel still matters
  // for the mocks, which reuse the default status names in every funnel.
  function getStage(stageKey, pipeline = null) {
    if (pipeline) {
      let s = getPipeline(pipeline)?.stages.find((s) => s.name === stageKey)
      if (s) return { ...s, pipeline }
    }
    return stagesByKey.value[stageKey]
  }

  // Display name of a stage. Stage keys are generated by the server, so the
  // key must never reach the screen; fall back to the key only for statuses
  // that do not belong to any funnel the user can see. Default stages are
  // stored in English ("Qualification"), so names go through translation.
  function stageLabel(stageKey, pipeline = null) {
    let label = getStage(stageKey, pipeline)?.deal_status
    return label ? __(label) : stageKey
  }

  // Who can own or be assigned a card of a funnel: its members and the admins
  // (crm.permissions.pipeline). Cached per funnel; reload() clears it.
  let assignableCache = {}
  let pipelineUsers = null
  async function assignableUsers(pipeline) {
    if (!pipeline) return null
    assignableCache[pipeline] ||= (async () => {
      pipelineUsers ||= apiCall('get_pipeline_users')
      let [config, users] = await Promise.all([
        apiCall('get_pipeline_config', { pipeline }),
        pipelineUsers,
      ])
      let names = new Set((config?.members || []).map((m) => m.user))
      for (let u of users?.users || []) if (u.is_admin) names.add(u.name)
      return [...names]
    })().catch((e) => {
      delete assignableCache[pipeline]
      throw e
    })
    return assignableCache[pipeline]
  }

  function setCurrentPipeline(name) {
    if (usingMocks.value) mockModule?.setMockPipeline(name)
  }

  return {
    pipelines,
    loaded,
    usingMocks,
    defaultPipeline,
    ensureLoaded,
    reload,
    getPipeline,
    getStage,
    stageLabel,
    setCurrentPipeline,
    assignableUsers,
    apiCall,
  }
})
